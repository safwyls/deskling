#!/usr/bin/env python3
"""Render the big clock digits as LVGL A8 (alpha-only) images: src/clock_digits.c.

A8 images are drawn in the object's image_recolor colour, so one set of digits serves any colour.
Each glyph is cropped to its own width (proportional); the firmware spaces them with a fixed gap.

usage: python3 tools/make_clock.py src/clock_digits.c [preview.png]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SETS = [
    # name, font, digit height in px (cap height of the figures)
    ("big", "/usr/share/fonts/opentype/inter/InterDisplay-Black.otf", 72),
    ("thin", "/usr/share/fonts/opentype/inter/InterDisplay-Thin.otf", 96),
]
CHARS = "0123456789:"
K = 4  # supersample


def render_set(font_path, height):
    # find the point size whose "0" is `height` px tall
    size = height
    for _ in range(4):
        f = ImageFont.truetype(font_path, size * K)
        box = f.getbbox("0")
        size = size * height / ((box[3] - box[1]) / K)
    f = ImageFont.truetype(font_path, int(round(size * K)))
    top = min(f.getbbox(c)[1] for c in "0123456789")
    bottom = max(f.getbbox(c)[3] for c in "0123456789")
    cell = max(f.getbbox(c)[2] - f.getbbox(c)[0] for c in "0123456789")
    out = {}
    for c in CHARS:
        b = f.getbbox(c)
        w = b[2] - b[0]
        im = Image.new("L", (w + 4 * K, bottom - top + 4 * K), 0)
        d = ImageDraw.Draw(im)
        x = (im.width - (b[2] - b[0])) // 2 - b[0]
        d.text((x, 2 * K - top), c, font=f, fill=255)
        im = im.resize((max(1, im.width // K), max(1, im.height // K)), Image.LANCZOS)
        out[c] = im
    return out


def c_name(set_name, c):
    return f"clock_{set_name}_{'colon' if c == ':' else c}"


def main():
    src = ["// Generated by tools/make_clock.py: big clock digits (A8, drawn in the image_recolor colour).",
           '#include "clock_digits.h"', ""]
    sheet_rows = []
    for name, path, h in SETS:
        imgs = render_set(path, h)
        row = []
        for c in CHARS:
            im = imgs[c]
            data = im.tobytes()
            src.append(f"static const uint8_t {c_name(name, c)}_map[] = {{{','.join('0x%02x' % v for v in data)}}};")
            src.append(f"const lv_image_dsc_t {c_name(name, c)} = {{\n"
                       f"  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .flags = 0, "
                       f".w = {im.width}, .h = {im.height}, .stride = {im.width} }},\n"
                       f"  .data_size = sizeof({c_name(name, c)}_map), .data = {c_name(name, c)}_map,\n}};")
            row.append(im)
        sheet_rows.append(row)
        print(f"{name}: cell {imgs['0'].size}, colon {imgs[':'].size}")
    src.append("const lv_image_dsc_t *const clock_big[11] = { " + ", ".join("&" + c_name("big", c) for c in CHARS) + " };")
    src.append("const lv_image_dsc_t *const clock_thin[11] = { " + ", ".join("&" + c_name("thin", c) for c in CHARS) + " };")
    open(sys.argv[1], "w").write("\n".join(src) + "\n")
    if len(sys.argv) > 2:
        W = max(sum(i.width + 6 for i in r) for r in sheet_rows) + 10
        H = sum(max(i.height for i in r) + 10 for r in sheet_rows) + 10
        sheet = Image.new("RGB", (W, H), (17, 26, 44))
        y = 10
        for r in sheet_rows:
            x = 10
            for im in r:
                col = Image.new("RGB", im.size, (159, 216, 247))
                sheet.paste(col, (x, y), im)
                x += im.width + 6
            y += max(i.height for i in r) + 10
        sheet.save(sys.argv[2])


if __name__ == "__main__":
    main()
